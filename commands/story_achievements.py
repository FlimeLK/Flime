async def _send_story_replay_with_videos(
    bot: Bot, chat_id: int, card_order: int, title: str, intro: str, choice: int, outcome: str
) -> None:
    """При повторному перегляді: відео з підписом де текст у межах ліміту, інакше текст окремо. Без "---"."""
    intro = _format_story_intro_blockquote(intro)
    start_pair = START_VIDEO_BY_CARD_ORDER.get(card_order)
    start_ok = False
    intro_as_caption = len(intro) <= CAPTION_MAX_LEN
    section_index = CARD_ORDER_TO_SECTION_INDEX.get(card_order, 0)
    start_photo = _resolve_section_start_photo(section_index) if section_index else None
    if start_photo:
        try:
            await bot.send_photo(
                chat_id=chat_id,
                photo=FSInputFile(start_photo),
                caption=emoji_to_premium(intro) if intro_as_caption else None,
                parse_mode="html" if intro_as_caption else None,
            )
            start_ok = True
        except Exception:
            pass
    if not start_ok and start_pair and USE_STORY_VIDEOS:
        path_start = _resolve_story_video(start_pair[0], start_pair[1])
        if os.path.isfile(path_start):
            try:
                if intro_as_caption:
                    await bot.send_video(
                        chat_id=chat_id, video=FSInputFile(path_start),
                        caption=emoji_to_premium(intro), parse_mode="html",
                    )
                else:
                    await bot.send_video(chat_id=chat_id, video=FSInputFile(path_start))
                start_ok = True
            except Exception:
                try:
                    await bot.send_video(chat_id=chat_id, video=FSInputFile(path_start))
                    start_ok = True
                except Exception:
                    pass
    if not start_ok or not intro_as_caption:
        await bot.send_message(chat_id=chat_id, text=emoji_to_premium(intro), parse_mode="html")
    outcome_as_caption = len(outcome) <= CAPTION_MAX_LEN
    raw_choice = VIDEO_BY_CARD_CHOICE.get((card_order, choice))
    path_choice = _resolve_video_path(raw_choice) if raw_choice else None
    choice_photo = None
    try:
        base_choices = CHOICES_BY_CARD_ORDER.get(card_order, [])
        if 1 <= int(choice) <= len(base_choices):
            choice_label = base_choices[int(choice) - 1][0]
            choice_photo = _resolve_choice_photo(card_order, choice_label)
    except Exception:
        choice_photo = None
    if choice_photo and os.path.isfile(choice_photo):
        try:
            if outcome_as_caption:
                await bot.send_photo(
                    chat_id=chat_id,
                    photo=FSInputFile(choice_photo),
                    caption=emoji_to_premium(outcome),
                    parse_mode="html",
                )
            else:
                await bot.send_photo(chat_id=chat_id, photo=FSInputFile(choice_photo))
                await bot.send_message(chat_id=chat_id, text=emoji_to_premium(outcome), parse_mode="html")
            return
        except Exception:
            pass
    if USE_STORY_VIDEOS and path_choice and os.path.isfile(path_choice):
        try:
            if outcome_as_caption:
                await bot.send_video(
                    chat_id=chat_id, video=FSInputFile(path_choice),
                    caption=emoji_to_premium(outcome), parse_mode="html",
                )
            else:
                await bot.send_video(chat_id=chat_id, video=FSInputFile(path_choice))
                await bot.send_message(chat_id=chat_id, text=emoji_to_premium(outcome), parse_mode="html")
        except Exception:
            try:
                await bot.send_video(chat_id=chat_id, video=FSInputFile(path_choice))
            except Exception:
                pass
            await bot.send_message(chat_id=chat_id, text=emoji_to_premium(outcome), parse_mode="html")
    else:
        await bot.send_message(chat_id=chat_id, text=emoji_to_premium(outcome), parse_mode="html")


