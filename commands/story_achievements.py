async def _send_story_card_photo(bot: Bot, chat_id: int, role_name: str) -> bool:
    """Надсилає фото карточки ролі з role_images перед текстом сюжетки. Повертає True якщо фото надіслано."""
    photo_path = os.path.join(ROLE_CARDS_IMAGES_DIR, f"{role_name}.jpg")
    if not os.path.isfile(photo_path):
        # Підтримка нової структури: Media/Розділ N/...
        image_exts = (".jpg", ".jpeg", ".png", ".webp")
        media_roots = (MEDIA_DIR, ROLE_MEDIA_DIR, UNIQUE_MEDIA_DIR, *SECTION_MEDIA_DIRS)
        photo_path = ""
        try:
            for root in media_roots:
                if not os.path.isdir(root):
                    continue
                for ext in image_exts:
                    direct = os.path.join(root, f"{role_name}{ext}")
                    if os.path.isfile(direct):
                        photo_path = direct
                        break
                if photo_path:
                    break
                for dirpath, _, filenames in os.walk(root):
                    for fname in filenames:
                        stem, ext = os.path.splitext(fname)
                        if ext.lower() not in image_exts:
                            continue
                        if stem == role_name:
                            photo_path = os.path.join(dirpath, fname)
                            break
                    if photo_path:
                        break
                if photo_path:
                    break
        except Exception:
            photo_path = ""
        if not photo_path:
            return False
    try:
        await bot.send_photo(chat_id=chat_id, photo=FSInputFile(photo_path))
        return True
    except Exception:
        return False


