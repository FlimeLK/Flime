def _resolve_unique_media_video(*must_contain: str) -> str:
    """Шлях до .mp4 у Media/Унікальні: ім'я файлу містить усі підрядки (без урахування регістру)."""
    needles = tuple(s.lower() for s in must_contain if s)
    if not needles:
        return os.path.join(UNIQUE_MEDIA_DIR, "missing.mp4")
    try:
        for fname in sorted(os.listdir(UNIQUE_MEDIA_DIR)):
            low = fname.lower()
            if not low.endswith(".mp4"):
                continue
            if all(n in low for n in needles):
                return os.path.join(UNIQUE_MEDIA_DIR, fname)
    except OSError:
        pass
    return os.path.join(UNIQUE_MEDIA_DIR, f"{needles[0]}_missing.mp4")


