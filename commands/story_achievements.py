def _can_progress_achievement_sequential(user_id: int, achievement_key: str) -> bool:
    """
    Обмеження: сюжетні досягнення з card_order виконуються ТІЛЬКИ ПО ЧЕРЗІ.
    Поки попереднє у ланцюжку не завершене (completed_at IS NOT NULL), наступні не накопичують прогрес.
    Звичайні досягнення без card_order (civilian, lucky, clown тощо) йдуть паралельно.
    """
    if not user_id:
        return False

    # Знайти meta про це досягнення серед ACHIEVEMENTS
    current_meta = next((a for a in ACHIEVEMENTS if a["key"] == achievement_key), None)
    if not current_meta:
        return False

    # Якщо досягнення не прив'язане до сюжетної картки - обмеження не діє
    current_order = current_meta.get("card_order")
    if current_order is None:
        return True

    if not _ensure_conn():
        return False

    # Усі сюжетні досягнення з меншим card_order - це "попередні" в ланцюжку
    prev_keys = [a["key"] for a in ACHIEVEMENTS
                 if a.get("card_order") is not None and a["key"] != achievement_key and a["card_order"] < current_order]
    if not prev_keys:
        return True

    # Перевіряємо, що КОЖНЕ попереднє досягнення завершено (completed_at IS NOT NULL)
    try:
        # Формуємо плейсхолдери (%s, %s, ...) для IN
        placeholders = ", ".join(["%s"] * len(prev_keys))
        query = (
            f"SELECT achievement_key, completed_at "
            f"FROM user_achievement_progress "
            f"WHERE user_id = %s AND achievement_key IN ({placeholders})"
        )
        rows = _db_fetchall(query, (user_id, *prev_keys))
    except Exception:
        return False

    completed_map = {r[0]: r[1] for r in rows}
    for key in prev_keys:
        completed_at = completed_map.get(key)
        # Немає запису або completed_at IS NULL → попереднє досягнення ще не виконано
        if not completed_at:
            return False
    return True

# Застарілі досягнення для видалення з БД
