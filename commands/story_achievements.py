        rows = _db_fetchall(
            "SELECT a.achievement_key, a.name_uk, a.condition_type, a.condition_role, a.target_value, "
            "COALESCE(u.current_value, 0), u.completed_at FROM achievements a "
            "LEFT JOIN user_achievement_progress u ON u.user_id = %s AND u.achievement_key = a.achievement_key "
            "ORDER BY a.id",
            (user_id,),
        )
