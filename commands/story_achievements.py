def _keyboard_story_cards(rows: list, user_id: int | None = None) -> InlineKeyboardMarkup:
    """Кнопки для вибору сюжету в /story: cards_show_{card_order}."""
    unlocked_orders = {int(card_order) for card_order, _ in rows}
    if user_id:
        owned_orders = _user_owned_story_card_orders(user_id)
        for order in CARD_ORDER_TO_SECTION_INDEX:
            o = int(order)
            if o in unlocked_orders:
                continue
            # Картка вже в колекції (/grant_cards тощо) - розділ відкритий навіть якщо перевірка передумов дає збій
            if o in owned_orders:
                unlocked_orders.add(o)
                continue
            if _is_story_card_order_unlocked(user_id, o):
                unlocked_orders.add(o)
    max_section = max(SECTION_INDEX_TO_CARD_ORDER.keys()) if SECTION_INDEX_TO_CARD_ORDER else 0
    buttons = []
    for idx in range(1, max_section + 1):
        card_order = SECTION_INDEX_TO_CARD_ORDER.get(idx)
        if card_order is None:
            continue
        if card_order in unlocked_orders:
            buttons.append(
                [InlineKeyboardButton(text=f"Розділ {idx}", callback_data=f"cards_show_{card_order}")]
            )
        else:
            buttons.append(
                [InlineKeyboardButton(text=f"🔒 Розділ {idx}", callback_data=f"story_locked_{idx}")]
            )
    buttons.append([InlineKeyboardButton(text="Повернутися", callback_data="profile_galicia_30s")])
    return InlineKeyboardMarkup(inline_keyboard=buttons)


