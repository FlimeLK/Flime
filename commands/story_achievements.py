            "INSERT INTO user_achievement_progress (user_id, achievement_key, current_value, completed_at) "
            "VALUES (%s, 'al_capone', 1, %s) ON CONFLICT (user_id, achievement_key) "
            "DO UPDATE SET current_value = 1, completed_at = EXCLUDED.completed_at",
            (user_id, datetime.utcnow()),
