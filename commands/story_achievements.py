def increment_achievement_progress(user_id: int, achievement_key: str) -> bool:
    """
    Нарахувати +1 до досягнення для користувача. Використовується для подій поза грою.
    Повертає True, якщо досягнення виконано.
    """
    if not _ensure_conn() or not user_id or not achievement_key:
        return False
    ensure_achievements_sync()
    try:
        # Для сюжетних досягнень з card_order - перевірка послідовності (по черзі)
        if not _can_progress_achievement_sequential(user_id, achievement_key):
            return False

        row = _db_fetchone(
            "SELECT achievement_key, name_uk, target_value, story_card_id FROM achievements WHERE achievement_key = %s",
            (achievement_key,),
        )
        if not row:
            return False
        akey, name_uk, target, card_id = row
        _db_execute(
            "INSERT INTO user_achievement_progress (user_id, achievement_key, current_value, completed_at) "
            "VALUES (%s, %s, 0, NULL) ON CONFLICT (user_id, achievement_key) DO NOTHING",
            (user_id, achievement_key),
        )
        _db_execute(
            "UPDATE user_achievement_progress SET current_value = current_value + 1 "
            "WHERE user_id = %s AND achievement_key = %s AND completed_at IS NULL",
            (user_id, achievement_key),
        )
        conn.commit()
        prog = _db_fetchone(
            "SELECT current_value, completed_at FROM user_achievement_progress WHERE user_id = %s AND achievement_key = %s",
            (user_id, achievement_key),
        )
        if not prog:
            return False
        current_value, completed_at = prog[0], prog[1]
        if current_value >= target and completed_at is None:
            _db_execute(
                "UPDATE user_achievement_progress SET completed_at = %s WHERE user_id = %s AND achievement_key = %s",
                (datetime.utcnow(), user_id, achievement_key),
            )
            conn.commit()
            return True
    except Exception:
        conn.rollback()
    return False


def _achievement_condition_matched(ctype: str, crole: str | None, role_name: str, is_winner: bool, killed: int, winner: str | None) -> bool:
    """Чи нараховувати +1 за цю гру для даного досягнення (за даними з roster_data)."""
    role_match = (crole or "").strip() == role_name
    if ctype == "wins_as_role":
        return role_match and is_winner
    if ctype == "wins_as_role_mafia_only":
        return role_match and winner == "mafia" and is_winner
    if ctype == "become_don":
        return role_name == "Аль Капоне"
    if ctype == "games_as_role":
        return role_match
    if ctype == "wins_total":
        return is_winner
    if ctype == "survived_games":
        return killed == 0
    return False


