# Інтро для повторного перегляду - завжди з констант (тексти, які ви прописали)
def _format_story_intro_blockquote(text: str) -> str:
    """
    Форматує інтродукцію сюжету:
    - шапка і дата лишаються звичайним текстом;
    - основна сюжетна частина загортається в blockquote;
    - "🚨 Вибір:" лишається поза цитатою.
    """
    if not text:
        return text
    markers = ("🚨 Вибір:", "❓Вибір:", "❓ Вибір:")
    marker = next((m for m in markers if m in text), None)
    if not marker:
        return text
    before, after = text.split(marker, 1)
    parts = before.strip().split("\n\n", 2)
    if len(parts) < 3:
        return text
    head, when_where, story = parts[0].strip(), parts[1].strip(), parts[2].strip()
    if not story:
        return text
    if not story.startswith("<blockquote"):
        story = f"<blockquote expandable>{story}</blockquote>"
    return f"{head}\n\n{when_where}\n\n{story}\n\n{marker}{after}"


def _format_story_outcome_blockquote(text: str) -> str:
    """Оформляє наслідок вибору як одну цитату."""
    if not text:
        return text
    body = text.strip()
    if body.startswith("<blockquote"):
        return body
    return f"<blockquote expandable>{body}</blockquote>"


def _format_unique_card_text_blockquote(text: str) -> str:
    """
    Унікальна картка:
    - 1-й блок: «💥ВИ ВІДКРИЛИ ЧАСТИНУ СЮЖЕТУ💥» (без цитати)
    - 2-й блок: заголовок ролі (без цитати)
    - решта тексту: в цитаті
    """
    if not text:
        return text
    parts = text.strip().split("\n\n", 2)
    if len(parts) < 3:
        return text
    head, title, body = parts[0].strip(), parts[1].strip(), parts[2].strip()
    if not body:
        return text
    if not body.startswith("<blockquote"):
        body = f"<blockquote expandable>{body}</blockquote>"
    return f"{head}\n\n{title}\n\n{body}"


